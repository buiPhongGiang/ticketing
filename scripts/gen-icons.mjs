// Regenerates app/src/icon-data.ts: the outline icons the guest app and the console draw, taken from Lucide
// (https://lucide.dev, ISC licence) so both use one family with one stroke. Nothing is fetched at run time and no
// icon package ships with the apps.
//   npm i lucide-static@0.460.0 --prefix /tmp/lucide && node scripts/gen-icons.mjs /tmp/lucide/node_modules/lucide-static
import fs from 'node:fs';
const src = process.argv[2];
if (!src) throw new Error('Pass the path of an installed lucide-static package.');
const names = [
  'house', 'store', 'ticket', 'scan-line', 'user', 'users', 'heart', 'message-circle', 'share-2', 'qr-code', 'wallet', 'receipt-text',
  'hourglass', 'circle-check', 'circle-x', 'clock', 'wifi-off', 'info', 'bell', 'calendar', 'map-pin', 'shield-check', 'flame', 'banknote',
  'chart-column', 'chevron-left', 'chevron-right', 'arrow-left', 'x', 'check', 'copy', 'external-link', 'plus', 'minus', 'refresh-cw', 'lock',
  'search', 'tag', 'link', 'pencil', 'triangle-alert', 'activity', 'repeat', 'send',
];
const out = {};
for (const name of names) {
  const svg = fs.readFileSync(`${src}/icons/${name}.svg`, 'utf8');
  out[name] = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]*?)\s*\/>/g)].map(([, tag, attrs]) =>
    [tag, Object.fromEntries([...attrs.matchAll(/([a-zA-Z][a-zA-Z0-9-]*)="([^"]*)"/g)].map(([, k, v]) => [k, v]))]);
  if (!out[name].length) throw new Error(`No shapes in ${name}`);
}
const version = JSON.parse(fs.readFileSync(`${src}/package.json`, 'utf8')).version;
fs.writeFileSync('app/src/icon-data.ts',
  `// Generated by scripts/gen-icons.mjs from lucide-static ${version} (ISC licence, https://lucide.dev). Do not edit by hand.\n` +
  '// Each icon is drawn on a 24 × 24 grid with a 2 px round stroke and no fill.\n' +
  'export type IconShape = readonly [tag: string, attrs: Readonly<Record<string, string>>];\n' +
  `export const iconData = ${JSON.stringify(out, null, 1)} as const satisfies Record<string, readonly IconShape[]>;\n` +
  'export type IconName = keyof typeof iconData;\n');
console.log(`${names.length} icons from lucide-static ${version}`);
